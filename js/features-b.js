  function kitchenState() {
    const k = kitchen(), n = nowMin(), c = toMin(k.time), b = toMin(k.breakfast);
    const fastLen = ((b - c) + 1440) % 1440 || 1440;
    const sinceClose = ((n - c) + 1440) % 1440;
    if (sinceClose < fastLen) return { closed: true, frac: sinceClose / fastLen, left: fastLen - sinceClose, k };
    const toClose = ((c - n) + 1440) % 1440;
    return { closed: false, frac: 1 - Math.min(1, toClose / 180), left: toClose, k };
  }
